import { app, BrowserWindow, ipcMain } from 'electron';
import path from 'path';
import bcrypt from 'bcryptjs';
import { fileURLToPath } from 'url';
import { createRequire } from 'module';
import * as dotenv from 'dotenv';

// setup ESM environment variables (equivalent to __filename and __dirname in CommonJS)
const require = createRequire(import.meta.url);
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// detect if the app is packaged (Production) or running in development
const isProd = app.isPackaged;

// DOTENV CONFIGURATION
// development - it reads from the root .env file.
// production - the .env file must be located in the 'resources' folder
if (isProd) {
  dotenv.config({ path: path.join(process.resourcesPath, '.env') });
} else {
  dotenv.config();
}

// access the database URL from environment variables
const DATABASE_URL = process.env.DATABASE_URL;

// PRISMA PATH SETUP
// define the location of node_modules. In production, Prisma binaries 
// are located in the 'resources' folder to avoid ASAR path issues.
const prismaRoot = isProd 
  ? path.join(process.resourcesPath, 'node_modules')
  : path.join(process.cwd(), 'node_modules');

// dynamically require PrismaClient from the specific root path
const { PrismaClient } = require(path.join(prismaRoot, '@prisma/client'));

// PRISMA CLIENT INITIALIZATION
// manually inject the DATABASE_URL and specify the exact path to the. query Engine binary for production environments.
const prisma = new PrismaClient({
  datasources: { db: { url: DATABASE_URL } },
  ...(isProd && {
    __internal: {
      engine: {
        binaryPath: path.join(prismaRoot, '.prisma/client/query_engine-windows.dll.node')
      }
    }
  })
});

// defines App's ID so Windows recognises the icon in Taskbar
app.setAppUserModelId("com.hammysden.app");

function createWindow() {
  const win = new BrowserWindow({
    width: 450,
    height: 550,
    useContentSize: true,
    resizable: false,       // disables stretching the screen
    maximizable: false,     // disables the maximize button
    fullscreenable: false,  // disables fullscreen
    frame: false,           // disables the default upper bar
    transparent: true,      // for the transparent corners

    icon: path.join(process.cwd(), 'src/renderer/assets/app-icon.ico'), // icon image

    webPreferences: {
      nodeIntegration: true,
      contextIsolation: false,
      sandbox: false,
    },
  });

  if (isProd) {
    // PRODUCTION MODE: load the index.html file generated by Vite in the 'dist' folder
    // the path is relative to the main.js file located inside 'dist'
    win.loadFile(path.join(__dirname, 'index.html'));
  } else {
    // DEVELOPMENT MODE: load the local development server URL provided by Vite
    win.loadURL('http://localhost:5173');
  }
}

app.whenReady().then(createWindow);

// close app if no windows are open
app.on('window-all-closed', () => {
  if (process.platform !== 'darwin') app.quit();
});

// for button exit app (closes app)
ipcMain.on('force-close', () => {
  app.quit();
});

// minimize window
ipcMain.on('minimize-app', () => {
  const win = BrowserWindow.getFocusedWindow();
  if (win) win.minimize();
});

