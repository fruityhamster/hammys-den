// LOGIN
// create account
ipcMain.handle('auth-signup', async (event, { name, email, password }) => {
  const saltRounds = 10;
  // generates the "hidden" password
  const hashedPassword = await bcrypt.hash(password, saltRounds);

  const generateUserCodeInitials = (fullName) => {
    const words = fullName.trim().toUpperCase().split(/\s+/);
    let initials = '';

    if (words.length >= 2) {
      initials = words[0][0] + words[words.length - 1][0];
    } else if (words.length === 1 && words[0].length >= 2) {
      initials = words[0].substring(0, 2);
    } else {
      initials = 'HM';
    }

    const randomNumber = Math.floor(100 + Math.random() * 900);
    return `${initials}-${randomNumber}`;
  };

  let generatedCode = generateUserCodeInitials(name);
  
  let existCode = await prisma.user.findUnique({ where: { userCode: generatedCode } });
  while (existCode) {
    generatedCode = generateUserCodeInitials(name);
    existCode = await prisma.user.findUnique({ where: { userCode: generatedCode } });
  }

  return await prisma.user.create({
    data: {
      name,
      email,
      password: hashedPassword, // saves the Hash, not the real password
      userCode: generatedCode,
    },
  });
});

// login
ipcMain.handle('auth-login', async (event, { email, password }) => {
  const user = await prisma.user.findUnique({ where: { email } });
  
  if (user) {
    // compares the written password with the saved hash
    const match = await bcrypt.compare(password, user.password);
    if (match) return user;
  }
  
  throw new Error('Access denied');
});

// SETTINGS - ACCOUNT 
// update user email
ipcMain.handle('update-user-email', async (event, { id, email }) => {
  try {
    const cleanEmail = email.trim();

    // verify is another user (different id) already uses this email
    const existingUserWithEmail = await prisma.user.findFirst({
      where: {
        email: cleanEmail,
        id: {
          not: id // different id from this account
        }
      }
    });

    if (existingUserWithEmail) {
      // if founds, error
      throw new Error('Email already in use');
    }

    // if not used, update
    const updatedUser = await prisma.user.update({
      where: { id: id },
      data: { email: cleanEmail }
    });

    // returns updated user
    return updatedUser;

  } catch (error) {
    console.error("Erro Prisma (update-user-email):", error);
    throw new Error(error.message || 'Error updating email');
  }
});